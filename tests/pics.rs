/// Find the wire length for one zero-valued object using the actual decoder. CA 2 is
/// deliberately absent from the database. A recognized control type gets a CA error
/// without starting any application procedure.
fn sample(id: TypeId, profile: Profile) -> Asdu {
    let mut bytes = [0; 255];
    bytes[0] = id.0;
    bytes[1] = 1;
    bytes[2] = Cause::ACTIVATION.value();
    bytes[2 + profile.cot.octets()] = 2;
    (profile.header_len() + profile.ioa.octets()..=usize::from(profile.max_asdu_len))
        .find_map(|len| Asdu::decode(&bytes[..len], &profile).ok())
        .unwrap_or_else(|| panic!("missing one-object sample for {id}"))
}

fn types_table(profile: Profile) -> String {
    let mut out = String::from("| ID | Type | Codec | Master receives | Outstation recognizes |\n|---:|---|---|---|---|\n");
    let mut server = Rig::new(database(), ServerConfig { profile, end_of_initialization: None, ..ServerConfig::default() });
    server.station.set_file_store(iec60870::station::MemoryFileStore::new());
    let conn = server.connect(GroupId(0));
    server.start(conn);
    let mut master = MasterRig::new(ClientConfig { profile, ..ClientConfig::default() });
    for n in 1..=127 {
        let id = TypeId(n);
        let mut asdu = sample(id, profile);
        let codec = if matches!(asdu.objects, Objects::Raw(_)) { "Raw" } else { "Typed" };
        if id == TypeId::F_SC_NA_1 {
            asdu.cot = Cot::REQUEST;
        } else if id == TypeId::F_AF_NA_1 {
            asdu.cot = Cot::FILE_TRANSFER;
        }
        server.send(conn, &asdu);
        let replies = server.take(conn);
        let [reply] = replies.as_slice() else { panic!("expected a single response for {id}") };
        let control = match reply.cot.cause {
            Cause::UNKNOWN_TYPE_ID => "No",
            Cause::UNKNOWN_COMMON_ADDRESS => "Yes",
            Cause::FILE_TRANSFER if id == TypeId::F_AF_NA_1 && reply.cot.negative => "Yes",
            cause => panic!("unexpected dispatch result for {id}: {cause}"),
        };

        asdu.cot = Cot::SPONTANEOUS;
        master.outstation.submit(&asdu.to_vec(&profile).unwrap(), master.now).unwrap();
        master.pump();
        let monitor = match master.events.as_slice() {
            [Event::Point(_)] => "Point",
            [Event::EndOfInitialization { .. }] => "Initialization",
            [Event::Asdu(_)] => "ASDU",
            events => panic!("unexpected unsolicited events for {id}: {events:?}"),
        };
        master.events.clear();
        if let Some(name) = id.name() {
            let permission = if profile.permits(id) { codec } else { "Outside profile" };
            writeln!(out, "| {n} | `{name}` | {permission} | {monitor} | {control} |").unwrap();
        } else {
            assert_eq!((codec, monitor, control), ("Raw", "ASDU", "No"), "reserved ID {n}");
        }
    }
    out
}

fn table(out: &mut String, label: &str, body: &str) {
    writeln!(out, "\n<div class=\"table-scroll\" role=\"region\" aria-label=\"{label}\" tabindex=\"0\">\n").unwrap();
    out.push_str(body);
    out.push_str("\n</div>\n");
}

fn render() -> String {
    let mut out = String::from(
        "+++\ntitle = \"Interoperability statement\"\ndescription = \"Look up the ASDU types, station behavior and default settings for IEC 101 and IEC 104.\"\nweight = 4\n[extra]\nnav_title = \"PICS and PIXIT\"\n+++\n\n<!-- Generated by tests/pics.rs. Edit the generator and regenerate. -->\n",
    );
    out.push_str("\nThe Protocol Implementation Conformance Statement (PICS) describes type and procedure support. The Protocol Implementation Extra Information for Testing (PIXIT) records the parameters to use when exercising that support.\n");
    out.push_str("\n## Procedure coverage\n\n");
    let coverage = cases::summary(cases::CASES);
    writeln!(out, "Of {} project cases, {} have tests covering the case, {} have partial coverage and {} have no test. {} include a lib60870-C peer. [Procedure evidence and gaps](@/docs/conformance.md).", coverage.cases, coverage.covered, coverage.partial, coverage.uncovered, coverage.interop).unwrap();
    out.push_str("\n<details>\n<summary>Test evidence by procedure</summary>\n\n");
    for case in cases::CASES {
        writeln!(out, "- **{}** · {}", case.id, case.procedure).unwrap();
        for test in case.tests {
            writeln!(out, "  - `{}::{}`", test.file, test.name).unwrap();
        }
        if let Some(gap) = &case.gap {
            writeln!(out, "  - Open · {}", gap.note).unwrap();
        }
    }
    out.push_str("\n</details>\n");
    out.push_str("\nFor file transfer, check the type tables for payload decoding and the procedure evidence for station support. Formal IEC test-case mapping and laboratory certification are pending.\n");
    out.push_str("\n## Link and station defaults\n");
    let mut widths = String::from("| Profile | Cause bytes | Common address bytes | Object address bytes | Maximum ASDU bytes |\n|---|---:|---:|---:|---:|\n");
    for (name, p) in [("IEC 101", Profile::IEC101), ("IEC 104", Profile::IEC104)] {
        writeln!(widths, "| {name} | {} | {} | {} | {} |", p.cot.octets(), p.ca.octets(), p.ioa.octets(), p.max_asdu_len).unwrap();
    }
    table(&mut out, "Default profile widths", &widths);
    let link = cs104::Config::default();
    writeln!(out, "\nIEC 104 uses TCP port {} or TLS port {}. Send window k is {} and acknowledgment window w is {}. Timers t0, t1, t2 and t3 are {:?}, {:?}, {:?} and {:?}.", cs104::DEFAULT_PORT, cs104::DEFAULT_TLS_PORT, link.k, link.w, link.t0, link.t1, link.t2, link.t3).unwrap();
    let link = cs101::Config::default();
    writeln!(out, "\nIEC 101 link address width in octets is {}. Response timeout is {:?}, with {} retries. The poll, reset and link-test intervals are {:?}, {:?} and {:?}. The character timeout is {:?} and idle gap is {:?}. Single-character acknowledgment is {}. Queue capacity is {} ASDUs per station and class.", link.address_width.octets(), link.response_timeout, link.retries, link.poll_interval, link.reset_interval, link.test_interval, link.char_timeout, link.idle_gap, link.single_char_ack, link.queue_len).unwrap();
    let client = ClientConfig::default();
    let server = ServerConfig::default();
    writeln!(out,"\nFile download limits are {} octets at the master and {} at the outstation. The outstation serves sections of {} octets and expires an idle selection after {:?}.", client.files.max_length,server.files.max_length,server.files.section_size,server.files.timeout).unwrap();
    writeln!(out, "\nThe master uses originator {}, confirmation timeout {:?} and termination timeout {:?}. Waiting for command termination is {}. Time-tagged commands are {}.", client.originator, client.confirmation_timeout, client.termination_timeout, client.command_termination, client.time_tagged_commands).unwrap();
    writeln!(out, "\nThe outstation buffers {} events per redundancy group. Select timeout is {:?} and cyclic period is {:?}. Background scanning is {}. End-of-initialization cause is {}.", server.event_capacity, server.select_timeout, server.cyclic_period, server.background_period.map_or_else(|| "off".into(), |d| format!("{d:?}")), server.end_of_initialization.map_or_else(|| "off".into(), |c| c.0.to_string())).unwrap();

    out.push_str("\n## Type support by direction\n\nEach row uses one object under the named ASDU profile. A file catalog is configured for the directory and file acknowledgment probes. **Master receives** shows the unsolicited event with no request pending. **ASDU** means the application receives the payload directly. **Outstation recognizes** means the station checked the common address or rejected a file acknowledgment without a selection. Successful procedures and their prerequisites are listed in the coverage report. Reserved IDs in 1–127 are probed and omitted from the tables.\n\nJump to [IEC 104](#iec-104) or [IEC 101](#iec-101).\n");
    for (label, p) in [("IEC 104", Profile::IEC104), ("IEC 101", Profile::IEC101)] {
        writeln!(out, "\n### {label}\n").unwrap();
        table(&mut out, &format!("{label} type support"), &types_table(p));
    }
    out.push_str("\n## Causes of transmission\n\nNamed and group causes recognized by the codec\n\n");
    for cause in (0..64).filter_map(Cause::new).filter(|c| c.is_standard()) {
        writeln!(out, "- {cause}").unwrap();
    }
    out.push_str(
        "\n## TLS parameters and deviations\n\nThe PEM configurations require mutual authentication. Enabled protocol versions in preference order are ",
    );
    let versions: Vec<_> = tls::PROTOCOL_VERSIONS.iter().map(|v| format!("`{:?}`", v.version)).collect();
    writeln!(out, "{}.\n\nOffered cipher suites in preference order\n", versions.join(", ")).unwrap();
    for suite in tls::CIPHER_SUITES {
        writeln!(out, "- `{:?}`", suite.suite()).unwrap();
    }
    out.push('\n');
    table(&mut out, "TLS profile deviations", include_str!("../src/tls/deviations.md"));
    out
}

#[test]
fn published_statement_matches_the_implementation() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let page = root.join("site/content/docs/pics.md");
    let expected = render();
    // The source archive omits the documentation site.
    if root.join("Cargo.toml.orig").is_file() && !root.join("site").exists() {
        return;
    }
    if std::env::var("IEC60870_BLESS").as_deref() == Ok("1") {
        std::fs::write(page, expected).unwrap();
    } else {
        assert!(
            std::fs::read_to_string(page).is_ok_and(|actual| actual == expected),
            "site/content/docs/pics.md is missing or stale; regenerate with IEC60870_BLESS=1 cargo test --locked --all-features --test pics"
        );
    }
}

#[test]
fn removing_a_permitted_type_changes_its_reported_behavior() {
    let profile = Profile::IEC104;
    let id = TypeId::M_SP_NA_1;
    assert!(types_table(profile).contains("| 1 | `M_SP_NA_1` | Typed | Point | No |"));
    let restricted = profile.with_types(profile.types.without(id));
    assert!(types_table(restricted).contains("| 1 | `M_SP_NA_1` | Outside profile | ASDU | No |"));
}
